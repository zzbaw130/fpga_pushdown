#!/usr/bin/env bash
# Create a self-contained PostgreSQL cluster at data/tpch_s<SF> and populate
# its tpch_s<SF> database through DuckDB's tpch and postgres extensions.
set -euo pipefail

usage() {
    cat <<'EOF'
Usage: create_tpch_db.sh --sf <positive integer> [--resume] [--force] [--keep-running] [--port <port>]

Creates data/tpch_s<SF> (the PostgreSQL cluster) and a database named
tpch_s<SF>.  Existing clusters are never touched unless --resume or --force
is supplied.  --resume imports only tables that have not already completed.
The cluster is stopped at the end unless --keep-running is supplied.
EOF
}

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PG_BIN="${PG_BIN:-${ROOT}/build/install/bin}"
DATA_ROOT="${PG_DATA_ROOT:-${ROOT}/data}"
SQL_DIR="${ROOT}/scripts/gen_data"
SF=""
FORCE=0
RESUME=0
KEEP_RUNNING=0
PORT=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --sf)
            SF="${2:-}"
            shift 2
            ;;
        --port)
            PORT="${2:-}"
            shift 2
            ;;
        --force)
            FORCE=1
            shift
            ;;
        --resume)
            RESUME=1
            shift
            ;;
        --keep-running)
            KEEP_RUNNING=1
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "Unknown argument: $1" >&2
            usage >&2
            exit 2
            ;;
    esac
done

if [[ ! "${SF}" =~ ^[1-9][0-9]*$ ]]; then
    echo "--sf must be a positive integer" >&2
    usage >&2
    exit 2
fi
for tool in initdb pg_ctl createdb psql; do
    if [[ ! -x "${PG_BIN}/${tool}" ]]; then
        echo "Missing ${PG_BIN}/${tool}; run scripts/build_postgres.sh first or set PG_BIN." >&2
        exit 1
    fi
done
command -v duckdb >/dev/null || { echo "duckdb is required" >&2; exit 1; }

DB_NAME="tpch_s${SF}"
PGDATA="${DATA_ROOT}/${DB_NAME}"
SOCKET_DIR="${ROOT}/.pgsock_${DB_NAME}"
LOG_FILE="${ROOT}/results/${DB_NAME}_create.log"
PORT="${PORT:-$((55432 + SF))}"
PG_USER="${PG_USER:-$(id -un)}"
NEW_CLUSTER=0

if [[ -e "${PGDATA}" ]]; then
    if [[ ${FORCE} -ne 1 && ${RESUME} -ne 1 ]]; then
        echo "${PGDATA} already exists; use --resume to continue or --force to replace it." >&2
        exit 1
    fi
    if [[ ${FORCE} -eq 1 ]]; then
        # --force is intentionally limited to this fully resolved, named cluster.
        "${PG_BIN}/pg_ctl" -D "${PGDATA}" -m immediate stop >/dev/null 2>&1 || true
        rm -rf -- "${PGDATA}"
        NEW_CLUSTER=1
    fi
else
    NEW_CLUSTER=1
fi

mkdir -p "${DATA_ROOT}" "${SOCKET_DIR}" "${ROOT}/results"
chmod 700 "${SOCKET_DIR}"
if [[ ${NEW_CLUSTER} -eq 1 ]]; then
    "${PG_BIN}/initdb" -D "${PGDATA}" --no-locale --encoding=UTF8 --auth=trust >/dev/null

    cat >> "${PGDATA}/postgresql.conf" <<EOF
# Generated by scripts/gen_data/create_tpch_db.sh
port = ${PORT}
listen_addresses = ''
unix_socket_directories = '${SOCKET_DIR}'
shared_buffers = '1GB'
maintenance_work_mem = '1GB'
max_wal_size = '8GB'
checkpoint_timeout = '30min'
EOF
fi

cleanup() {
    if [[ ${KEEP_RUNNING} -eq 0 ]]; then
        "${PG_BIN}/pg_ctl" -D "${PGDATA}" -m fast stop >/dev/null 2>&1 || true
    fi
}
trap cleanup EXIT

if ! "${PG_BIN}/pg_ctl" -D "${PGDATA}" status >/dev/null 2>&1; then
    "${PG_BIN}/pg_ctl" -D "${PGDATA}" -l "${LOG_FILE}" -w start >/dev/null
fi
if ! "${PG_BIN}/psql" -h "${SOCKET_DIR}" -p "${PORT}" -d postgres -Atqc \
    "SELECT 1 FROM pg_database WHERE datname = '${DB_NAME}'" | grep -qx 1; then
    "${PG_BIN}/createdb" -h "${SOCKET_DIR}" -p "${PORT}" "${DB_NAME}"
fi

PSQL=("${PG_BIN}/psql" -v ON_ERROR_STOP=1 -h "${SOCKET_DIR}" -p "${PORT}" -d "${DB_NAME}")
if ! "${PSQL[@]}" -Atqc "SELECT to_regclass('public.region')" | grep -qx region; then
    "${PSQL[@]}" -f "${SQL_DIR}/create_tables.sql"
fi

# Keep the table order explicit: it mirrors create_tables.sql and prevents
# foreign-key creation from seeing partially populated parent tables.
DUCKDB_SQL="LOAD tpch; LOAD postgres; CALL dbgen(sf=${SF});"
DUCKDB_SQL+=" ATTACH 'host=${SOCKET_DIR} port=${PORT} dbname=${DB_NAME} user=${PG_USER}' AS pg (TYPE POSTGRES);"
PENDING_TABLES=0
for table in region nation part supplier partsupp customer orders lineitem; do
    existing_rows="$("${PSQL[@]}" -Atqc "SELECT count(*) FROM ${table}")"
    if [[ "${existing_rows}" == "0" ]]; then
        DUCKDB_SQL+=" INSERT INTO pg.public.${table} SELECT * FROM ${table};"
        PENDING_TABLES=1
    else
        echo "Keeping existing ${table} (${existing_rows} rows)."
    fi
done
if [[ ${PENDING_TABLES} -eq 1 ]]; then
    duckdb -c "${DUCKDB_SQL}"
fi

"${PSQL[@]}" -f "${SQL_DIR}/primary_keys.sql"
"${PSQL[@]}" -f "${SQL_DIR}/foreign_keys.sql"
"${PSQL[@]}" -f "${SQL_DIR}/create_indexes.sql"
"${PSQL[@]}" -c 'ANALYZE;'
"${PSQL[@]}" -Atc "SELECT 'lineitem_rows=' || count(*) FROM lineitem;"

echo "Created ${DB_NAME}: PGDATA=${PGDATA}, port=${PORT}"
if [[ ${KEEP_RUNNING} -eq 0 ]]; then
    echo "The cluster has been stopped. Add --keep-running to leave it available."
fi
